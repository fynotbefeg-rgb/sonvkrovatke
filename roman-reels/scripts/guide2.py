def h(t, l=1): d.add_heading(t, level=l)
def p(t, b=False, i=False):
    para = d.add_paragraph(); r = para.add_run(t); r.bold = b; r.italic = i
def bl(xs):
    for x in xs: d.add_paragraph(x, style="List Bullet")
def nl(xs):
    for x in xs: d.add_paragraph(x, style="List Number")
def table(head, rows):
    t = d.add_table(rows=1, cols=len(head)); t.style = "Light Grid Accent 1"
    for c, x in zip(t.rows[0].cells, head): c.text = x
    for r in rows:
        for c, x in zip(t.add_row().cells, r): c.text = str(x)
    d.add_paragraph()

