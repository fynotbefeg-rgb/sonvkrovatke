"""Как мы работаем: Виктор, Роман и Claude — процесс создания рилсов."""
import sys
from docx import Document
from docx.shared import Pt, RGBColor
d = Document(); st = d.styles["Normal"]; st.font.name = "Arial"; st.font.size = Pt(11)
def p(t, b=False, i=False, gray=False):
    r = d.add_paragraph().add_run(t); r.bold = b; r.italic = i
    if gray: r.font.color.rgb = RGBColor(110, 110, 110)
def li(t, num=False): d.add_paragraph(t, style="List Number" if num else "List Bullet")
def table(rows, head):
    t = d.add_table(rows=1, cols=len(head)); t.style = "Table Grid"
    for c, x in zip(t.rows[0].cells, head): c.text = x; c.paragraphs[0].runs[0].bold = True
    for r in rows:
        for c, x in zip(t.add_row().cells, r): c.text = x
    d.add_paragraph()

