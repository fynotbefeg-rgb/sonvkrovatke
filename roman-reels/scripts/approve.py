from docx import Document
from docx.shared import Pt, RGBColor

d = Document()
st = d.styles["Normal"]; st.font.name = "Arial"; st.font.size = Pt(12)

def p(t, b=False, i=False, color=None):
    para = d.add_paragraph(); r = para.add_run(t); r.bold = b; r.italic = i
    if color: r.font.color.rgb = RGBColor(*color)

def topic(n, title, hooks, body, dur):
    d.add_heading(f"Рилс {n}. {title}", 1)
    p(f"Длительность: {dur}", i=True)
    d.add_heading("Хуки (первые 5–7 секунд, 3 варианта для теста)", 2)
    for k, x in enumerate(hooks, 1):
        p(f"Хук {k}: {x}")
    d.add_heading("Основной текст", 2)
    for x in body:
        p(x)

d.add_heading("Сценарии рилсов на согласование", 0)
