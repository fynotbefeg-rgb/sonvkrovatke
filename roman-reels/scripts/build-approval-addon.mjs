#!/usr/bin/env node
// Build an additive installer without changing or fetching the old remote code.
import {readFileSync, writeFileSync} from 'node:fs';

const source = readFileSync(new URL('../apps-script/Code.gs', import.meta.url), 'utf8');
const implementation = source.replace(/^\/\/ Replace[^\n]*\n/, '');
const addon = `// Generated by scripts/build-approval-addon.mjs. No secrets in this file.
// Add as RomanApproval.gs. First rename OLD doPost to legacyDoPost in Code.gs.
// Do not install together with the full replacement Code.gs from this repository.
const RomanApprovalV1 = (function() {
${implementation}
return {doPost: doPost, onRomanApprovalEdit: onRomanApprovalEdit,
  setupRomanApproval: setupRomanApproval, queue: getApprovedProductionQueue,
  safety: checkProductionSafety};
})();

function doPost(e) { return RomanApprovalV1.doPost(e); }
function onRomanApprovalEdit(e) { return RomanApprovalV1.onRomanApprovalEdit(e); }
function setupRomanApproval() { return RomanApprovalV1.setupRomanApproval(); }
function romanApprovalQueueV1() { return RomanApprovalV1.queue(); }
function romanApprovalSafetyV1() { return RomanApprovalV1.safety(); }
`;
writeFileSync(new URL('../apps-script/RomanApproval.gs', import.meta.url), addon);
console.log('Built additive approval file. No remote code changed.');
