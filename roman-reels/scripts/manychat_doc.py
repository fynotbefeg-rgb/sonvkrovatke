"""Инструкция Роману: настройка ManyChat под рилс (слово «БОТ»)."""
import sys
from docx import Document
from docx.shared import Pt, RGBColor
d = Document()
st = d.styles["Normal"]; st.font.name = "Arial"; st.font.size = Pt(12)
def p(t, b=False, i=False, gray=False):
    para = d.add_paragraph(); r = para.add_run(t); r.bold = b; r.italic = i
    if gray: r.font.color.rgb = RGBColor(110, 110, 110)
def li(t, num=False): d.add_paragraph(t, style="List Number" if num else "List Bullet")

d.add_heading("Настройка ManyChat под рилс", 0)
p("Чтобы рилс сработал, ManyChat нужно настроить до публикации. Иначе люди напишут «БОТ» и ничего не получат. Займёт 15–20 минут.", i=True)
p("Перед началом включи запись экрана. Эти записи вставим в ролик, будет видно настоящую настройку. Ошибки и паузы не страшны — всё вырежем.", b=True)

d.add_heading("1. Инстаграм", 1)
li("Аккаунт должен быть профессиональным (бизнес или автор). Проверить: Настройки → «Тип аккаунта и инструменты».")
li("Настройки → «Сообщения и ответы на истории» → включи «Разрешить доступ к сообщениям» (пункт про подключённые приложения). Без этого ManyChat не сможет писать в директ.")

d.add_heading("2. ManyChat", 1)
li("Зайди на manychat.com → «Get started» → выбери Instagram.")
li("Вход через Meta / Фейсбук — пароль от Инстаграма никому не передаёшь. Дай все разрешения, которые он попросит.")

d.add_heading("3. Автоматизация", 1)
li("Automations → New Automation → шаблон с ответом в директ на комментарий («auto-DM from comments» или похожее).", True)
li("Пост: «следующий пост» или «любой пост/рилс».", True)
li("Кодовое слово: БОТ (если попросит — добавь варианты «бот» и «Бот»).", True)
li("Публичный ответ под комментарием: «Отправил в директ 📩».", True)
li("Сообщение в директ — текст ниже.", True)
li("Включи автоматизацию (Go Live / Set Live).", True)

d.add_heading("4. Проверка", 1)
li("Со второго аккаунта напиши «БОТ» под любым своим рилсом.")
li("Директ должен прийти за несколько секунд. Если не пришёл — пришли скрин, разберёмся.")

d.add_heading("Текст для директа", 1)
for x in ["Привет! Держи инструкцию 👇",
          "1. Переведи Инстаграм в профессиональный аккаунт (бизнес или автор).",
          "2. В настройках сообщений включи «Разрешить доступ к сообщениям».",
          "3. Зарегистрируйся на manychat.com и подключи Инстаграм через вход Meta.",
          "4. Создай автоматизацию из шаблона ответа на комментарий: выбери рилс и кодовое слово.",
          "5. Напиши публичный ответ и сообщение в директ со ссылкой или кнопкой.",
          "6. Включи и проверь со второго аккаунта.",
          "Если что-то не получится — пиши сюда, подскажу 🙌"]:
    p(x)

d.add_heading("Важно про тариф", 1)
p("На бесплатном тарифе ManyChat есть лимит контактов в месяц — по последним данным около 25. Посмотри в кабинете, какой у тебя. Если рилс залетит, бесплатного не хватит: после лимита бот перестанет отвечать. Лучше заранее решить, берём ли платный тариф.")

d.add_heading("Что прислать после настройки", 1)
li("Записи экрана.")
li("Скрин с названиями кнопок — если они отличаются от сценария, поправим текст до генерации в HeyGen.")
p("Названия кнопок указаны по инструкциям из интернета и могут немного отличаться в твоём кабинете.", i=True, gray=True)
d.save(sys.argv[1])
