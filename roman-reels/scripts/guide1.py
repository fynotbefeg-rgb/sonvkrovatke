def h(t, l=1): d.add_heading(t, level=l)
def p(t, b=False, i=False):
    para = d.add_paragraph(); r = para.add_run(t); r.bold = b; r.italic = i; return para
def bl(items):
    for x in items: d.add_paragraph(x, style="List Bullet")
def nl(items):
    for x in items: d.add_paragraph(x, style="List Number")
def table(head, rows, widths=None):
    t = d.add_table(rows=1, cols=len(head)); t.style = "Light Grid Accent 1"
    for c, x in zip(t.rows[0].cells, head): c.text = x
    for r in rows:
        cells = t.add_row().cells
        for c, x in zip(cells, r): c.text = str(x)
    d.add_paragraph()

